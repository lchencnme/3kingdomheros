#!/usr/bin/env python3
"""YJ4-lite score compiler (design doc 14, fallback path: text score -> engine data).

Score: content/music/*.json, per channel a text line of NOTE:TICKS tokens ('|' = bar line, checked
against ticks_per_bar). NOTE is C2..B9 with optional #, '-' = rest, for ch4 'K<vol>' = noise hit.
Output (unbanked, read by the bank-0 timer ISR): per-channel streams of (note, ticks, gate) triples,
0xFF = end of stream (loop). Also the 96-entry pulse/wave frequency-register tables (14.1 formulas).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAMES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
REST, END = 0xFE, 0xFF


def die(m):
    sys.exit("gen_music: " + m)


def note_index(tok):
    """C2 = 0 ... B9 = 95"""
    n = NAMES[tok[0]]
    i = 1
    if tok[i] == "#":
        n += 1
        i += 1
    octave = int(tok[i:])
    v = (octave - 2) * 12 + n
    if not 0 <= v <= 95:
        die(f"note out of range {tok}")
    return v


def freq(n):
    return 65.40639 * 2 ** (n / 12)


def regs():
    pulse, wave = [], []
    for n in range(96):
        f = freq(n)
        pulse.append(max(0, min(2047, round(2048 - 131072 / f))))
        wave.append(max(0, min(2047, round(2048 - 65536 / f))))
    return pulse, wave


def compile_channel(ch, line, inst, tpb):
    out = []
    for bar_i, bar in enumerate(line.split("|")):
        total = 0
        for tok in bar.split():
            name, ticks = tok.split(":")
            ticks = int(ticks)
            if not 1 <= ticks <= 255:
                die(f"{ch} bar {bar_i + 1}: ticks {ticks}")
            total += ticks
            if name == "-":
                out += [REST, ticks, 0]
                continue
            if ch == "ch4":
                if name[0] != "K":
                    die("ch4 only takes K<vol>")
                out += [int(name[1:]) & 15, ticks, max(1, int(ticks * inst["gate"]))]
                continue
            n = note_index(name)
            if ch == "ch3" and n > 47:
                die(f"wave channel limited to C2..B5: {name}")
            if ch in ("ch1", "ch2") and n > 59:
                die(f"pulse channels limited to C2..B6: {name}")
            out += [n, ticks, max(1, min(ticks, round(ticks * inst["gate"])))]
        if total != tpb:
            die(f"{ch} bar {bar_i + 1} has {total} ticks, expected {tpb}")
    out.append(END)
    return out


def main():
    songs = sorted((ROOT / "content" / "music").glob("*.json"))
    pulse, wave = regs()
    h = ["/* GENERATED by tools/gen_music.py - do not edit */", "#ifndef MUSIC_DATA_H", "#define MUSIC_DATA_H",
         "#include <stdint.h>", "#define MUS_REST 0xFEu", "#define MUS_END 0xFFu",
         "typedef struct { uint8_t bpm; const uint8_t *ch[4]; uint8_t duty1, vol1, env1, duty2, vol2, env2, vol3, noise4, env4; } Song;",
         "extern const uint16_t mus_pulse_reg[96];", "extern const uint16_t mus_wave_reg[96];",
         "extern const uint8_t mus_wave_soft[16];",
         "#define MUSIC_BANK 17u   /* songs live in ROM bank 17; the audio ISR maps it while it reads */"]
    c = ['#include "music_data.h"']
    c.append("const uint16_t mus_pulse_reg[96] = {" + ", ".join(map(str, pulse)) + "};")
    c.append("const uint16_t mus_wave_reg[96] = {" + ", ".join(map(str, wave)) + "};")
    # soft wave: half-sine-ish 32 x 4-bit samples packed
    import math
    smp = [round(7.5 + 7.5 * math.sin(2 * math.pi * i / 32)) for i in range(32)]
    c.append("const uint8_t mus_wave_soft[16] = {" + ", ".join(str((smp[2 * i] << 4) | smp[2 * i + 1]) for i in range(16)) + "};")
    table = []
    cs = ["#pragma bank 17   /* song data: read by the audio ISR with bank 17 mapped (audio.c) */", '#include "music_data.h"']
    for k, sp in enumerate(songs):
        s = json.loads(sp.read_text(encoding="utf-8"))
        tpb = s["ticks_per_bar"]
        ins = s["instruments"]
        streams = {}
        for ch in ("ch1", "ch2", "ch3", "ch4"):
            cd = s["channels"][ch]
            streams[ch] = compile_channel(ch, cd["notes"], ins[cd["inst"]], tpb)
            cs.append(f"static const uint8_t {s['id'].lower()}_{ch}[] = {{" + ", ".join(map(str, streams[ch])) + "};")
        bars = [len(s["channels"][ch]["notes"].split("|")) for ch in streams]
        if len(set(bars)) != 1:
            die(f"{sp.name}: channels have different bar counts {bars}")
        if not 1 <= s["bpm"] <= 240:
            die("bpm must be 1..240 (at most 2 ticks per 64 Hz step at 24 ticks/quarter)")
        L, P, B, D = ins[s["channels"]["ch1"]["inst"]], ins[s["channels"]["ch2"]["inst"]], ins[s["channels"]["ch3"]["inst"]], ins[s["channels"]["ch4"]["inst"]]
        cs.append(f"const Song {s['id'].lower()} = {{{s['bpm']}, {{{', '.join(s['id'].lower() + '_' + ch for ch in streams)}}}, "
                 f"{L['duty']}, {L['volume']}, {L['env_down']}, {P['duty']}, {P['volume']}, {P['env_down']}, {B['volume']}, {D['noise']}, {D['env_down']}}};")
        h.append(f"extern const Song {s['id'].lower()};   /* {s['name']} */")
        h.append(f"#define MUS_{s['id'][5:]} {k}u")
        table.append(s["id"].lower())
        print(f"gen_music: {s['id']} {s['name']}: {bars[0]} bars, {sum(len(v) for v in streams.values())} bytes")
    h.append(f"#define MUS_COUNT {len(table)}u")
    h.append("extern const Song *const mus_songs[MUS_COUNT];   /* by MUS_* id (scripts, battle definitions) */")
    c.append("const Song *const mus_songs[MUS_COUNT] = {" + ", ".join("&" + n for n in table) + "};")
    h.append("#endif")
    (ROOT / "src/gen/music_data.h").write_text("\n".join(h) + "\n", encoding="utf-8")
    (ROOT / "src/gen/music_data.c").write_text("\n".join(c) + "\n", encoding="utf-8")
    (ROOT / "src/gen/music_songs.c").write_text("\n".join(cs) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
